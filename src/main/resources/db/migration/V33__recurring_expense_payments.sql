-- Expand step (TEN-503): record which months a recurring bill has been paid for, so a bill whose
-- due date has passed can stay in Needs attention until it is paid instead of dropping out.
--
-- Expand-contract: a new table only. Nothing is renamed, dropped or retyped, and code deployed
-- before this migration never reads it, so old and new application versions both work against
-- this shape. No backfill: with no row, every bill reads as unpaid, which is what the API said
-- before. Run scripts/backup-before-migrate.sh (or .ps1) first regardless: the rule is the rule.
--
-- One row per (bill, month), and the UNIQUE constraint is the idempotency mechanism, not an index
-- for reads: marking a paid month again is INSERT ... ON CONFLICT DO NOTHING, so two overlapping
-- requests cannot produce two rows and the database, not the application, decides. Its index also
-- serves every read: the list query walks idx_recurring_user (V4) for the user's bills and probes
-- this index per bill for the month, so no separate index on payment_month is added.
--
-- payment_month is 'YYYY-MM' in Asia/Manila, the same representation as budgets.budget_month.
-- A month is the granularity on purpose: a WEEKLY bill is paid or unpaid for its month as a whole.
--
-- ON DELETE CASCADE because recurring expenses are removed with a plain DELETE (and with their
-- user, by the cascade on recurring_expenses.user_id); a payment never outlives its bill.
CREATE TABLE recurring_expense_payments (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurring_expense_id  BIGINT      NOT NULL REFERENCES recurring_expenses(id) ON DELETE CASCADE,
    payment_month         VARCHAR(7)  NOT NULL,
    paid_at               TIMESTAMP   NOT NULL,
    CONSTRAINT uq_recurring_expense_payments_bill_month UNIQUE (recurring_expense_id, payment_month),
    CONSTRAINT ck_recurring_expense_payments_month CHECK (payment_month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$')
);


-- TIMESTAMP has no zone of its own, so the column states which one it holds (as V32 does for users).
COMMENT ON COLUMN recurring_expense_payments.paid_at IS
    'When the month was marked paid, in UTC. TIMESTAMP without time zone, so the zone is this convention, not the type.';
